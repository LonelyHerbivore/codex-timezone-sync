#!/usr/bin/env python3
"""Embed the self-contained UI in the native plugin; no external browser assets."""
from pathlib import Path
root=Path(__file__).resolve().parent
raw=(root/'dashboard.html').read_bytes()
numbers=[str(n) for n in raw]
(root/'dashboard_bundle.h').write_text('/* Auto-generated by embed_ui.py; do not edit. */\n'
    'static const unsigned char dashboard_html[] = {\n' +
    '\n'.join('  '+', '.join(numbers[i:i+20])+',' for i in range(0,len(numbers),20)) +
    '\n};\nstatic const size_t dashboard_html_size = sizeof(dashboard_html);\n')
